// ACCESSION — the policies' cards (BUILD.md §10.2): each policy's rules in order and its
// weights, as text for reports and as tools/policies/README.md, which is generated from them
// (`node tools/sim.js --cards --write`) and never edited by hand. A classic script, loaded
// after lib.js into the hardened core context.
//
//   Cards.text(name, policy) → the card as plain lines, for a report
//   Cards.readme(list?) → the README, for every registered policy (Policies.list()) or list
'use strict';
const Cards = (() => {
  const weights = card => card.weights && card.weights.length ? card.weights.map(([k, v]) => `${k} ${v}`).join(', ') : 'none';

  function text(name, policy) {
    const c = policy.card, lines = [`${name}: ${c.summary}`];
    c.rules.forEach((r, i) => lines.push(`  ${i + 1}. ${r}`));
    lines.push(`  Weights: ${weights(c)}.`);
    if (policy.kit) lines.push(`  Kit: ${kitWords(policy.kit)}.`);
    return lines.join('\n');
  }
  function kitWords(kit) {
    const out = [];
    for (const slot of ['weapon', 'garment']) {
      const k = kit[slot];
      if (!k) continue;
      const bits = [];
      if (k.form) bits.push(k.form);
      if (k.tier !== undefined) bits.push('tier ' + k.tier);
      if (k.level) bits.push('level ' + k.level);
      out.push(`${slot} ${bits.join(' ')}`.trim());
    }
    return out.join('; ');
  }

  function readme(list) {
    list = list || Policies.list();
    const out = [
      '# Policies',
      '',
      '*Generated by `node tools/sim.js --cards --write` from each policy\'s card (BUILD.md §10.2). Do not edit it by hand: change the card in the policy\'s file and regenerate it.*',
      '',
      'A policy sees only what a player sees: the view model with the events of its last action that took time, the labels it reads (within reading distance for a paragraph), the log, and the legal actions, the player\'s buttons. Its only source of chance is its own stream, `policy/<name>/<seed>`, which is never part of the game\'s state, so two runs on one seed make the same decisions. Each decision comes with one line saying why, which the sim logs. The helpers they share are in `lib.js` (`Obs`), and `cards.js` writes this file.',
      '',
      'Each card gives the policy\'s rules in the order it applies them, and its weights.',
    ];
    let group = null;
    for (const { name, group: g, policy } of list) {
      if (g !== group) { out.push('', `## ${g}`); group = g; }
      const c = policy.card;
      out.push('', `### ${name}`, '', c.summary, '');
      c.rules.forEach((r, i) => out.push(`${i + 1}. ${r}`));
      out.push('', `Weights: ${weights(c)}.`);
      if (policy.kit) out.push('', `Kit: ${kitWords(policy.kit)}.`);
    }
    return out.join('\n') + '\n';
  }

  return { text, readme };
})();
