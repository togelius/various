  function chain(chunks) {
    var h = chunks[0].length, out = [], y, c;
    for (y = 0; y < h; y++) {
      var s = '';
      for (c = 0; c < chunks.length; c++) s += chunks[c][y];
      out.push(s);
    }
    return out;
  }

