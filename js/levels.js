/* VANGUARD ZERO - stage layouts.
 *
 * Each stage is a list of 32-column chunks, 16 rows tall, joined left to right.
 * Authoring in fixed-width chunks keeps the maps legible and makes it obvious
 * where one design beat ends and the next begins.
 *
 *   #  solid      =  one-way platform   c  crumbling block
 *   ^  floor spikes   v  ceiling spikes   [ ] wall spikes
 *   ~  liquid (fatal) >  conveyor right  {  conveyor left
 *   |  boss door (open until the fight starts)
 *   P  start    K  checkpoint   X  exit    B  boss trigger
 *   T trooper  D drone  O hopper  S shielder  U turret  A ceiling turret
 *   R roller   F flame vent
 *   H health   @ big health   E weapon energy   1 extra life
 */
